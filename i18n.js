export function supportedLanguages() {
  return ['en', 'pt-PT'];
}

export function resolveLanguage(prefs) {
  if (prefs && prefs.explicitLanguage && prefs.language) return prefs.language;
  if (typeof navigator !== 'undefined' && navigator.languages) {
    for (let i = 0; i < navigator.languages.length; i++) {
      const tag = String(navigator.languages[i] || '').toLowerCase();
      if (tag.indexOf('pt') === 0) return 'pt-PT';
      if (tag.indexOf('en') === 0) return 'en';
    }
  }
  return 'en';
}

export function createI18n(initialLang) {
  let lang = initialLang || 'en';
  function t(key, vars) {
    const table = catalogues[lang] || catalogues.en;
    const fallback = catalogues.en;
    let text = table[key];
    if (text === undefined) text = fallback[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        text = text.split(`{${k}}`).join(String(vars[k]));
      });
    }
    return text;
  }
  return {
    get lang() {
      return lang;
    },
    setLang(next) {
      lang = supportedLanguages().indexOf(next) >= 0 ? next : 'en';
      if (typeof document !== 'undefined') document.documentElement.lang = lang === 'pt-PT' ? 'pt' : 'en';
    },
    t,
    movement(id) {
      return {
        name: t(`move.${id}.name`),
        title: t(`move.${id}.title`),
        tip: t(`move.${id}.tip`),
      };
    },
    movementIds,
    sheetLabels() {
      return {
        binding: t('sheet.binding'),
        clip: t('sheet.clip'),
        calibration: t('sheet.calibration'),
        footer: t('sheet.footer'),
        pageOf: (page, total) => t('sheet.pageOf', { page, total }),
      };
    },
  };
}